/// Categories and starter keywords inserted when the database is created,
/// and kept in sync with this list on every open (see `AppDatabase`).
///
/// Keywords are matched by `CategoryClassifier` at the start of a word of
/// the upper-case item name, so stems work (`MOZZ` → `MOZZ.TRIS`,
/// `MOZZARELLA`), and the keyword that comes first in the name wins. Keep
/// them generic grocery words, abbreviations as receipts print them and
/// widely sold brands that belong to one category; never store brands
/// (`ESSELUNGA`, `CRF`), which cover every aisle. User corrections will be
/// stored in `product_aliases` and take priority.
class CategorySeed {
  const new(this.name, this.icon, this.color, this.keywords);

  final String name;
  final String icon;
  final int color;
  final List<String> keywords;
}

